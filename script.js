function makeSeatLayout(total){
 const cx=340, cy=286, outer=256, inner=128, spacing=20;
 const vertical=spacing*Math.sqrt(3)/2;
 const seats=[];
 let row=0;
 for(let y=cy-outer; y<=cy; y+=vertical){
  const offset=(row%2)?spacing/2:0;
  for(let x=cx-outer; x<=cx+outer; x+=spacing){
   const xx=x+offset;
   const dx=xx-cx, dy=y-cy;
   const r=Math.hypot(dx,dy);
   if(dy<=0 && r>=inner && r<=outer){
    const theta=Math.atan2(cy-y, xx-cx); // 0 = droite, PI = gauche
    seats.push({x:xx,y:y,theta:theta});
   }
  }
  row++;
 }
 if(seats.length!==total){
  console.warn('Seat layout count mismatch', seats.length, total);
 }
 seats.sort((a,b)=>b.theta-a.theta || a.y-b.y || a.x-b.x);
 return seats;
}
